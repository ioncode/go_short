// Package pool предоставляет типобезопасную обёртку над стандартным [sync.Pool]
// для повторного использования объектов, поддерживающих сброс состояния.
//
// Перед возвратом объекта в пул через метод [Pool.Put] автоматически вызывается
// его метод Reset, что исключает утечку данных между переиспользованиями.
//
// Пример использования:
//
//	p := pool.New(func() *MyStruct {
//		return &MyStruct{Data: make([]byte, 0, 1024)}
//	})
//
//	obj := p.Get()
//	defer p.Put(obj)
package pool

import "sync"

// Resetter описывает ограничение (constraint) для типов, состояние которых
// можно сбросить к исходному перед повторным использованием.
type Resetter interface {
	// Reset приводит состояние объекта к начальному виду, сохраняя
	// при необходимости уже выделенную память (например, capacity слайсов).
	Reset()
}

// Pool представляет собой потокобезопасный пул для хранения и переиспользования
// объектов одного конкретного типа T, реализующего интерфейс [Resetter].
//
// Нулевое значение Pool не готово к использованию без фабричной функции,
// поэтому для создания экземпляра рекомендуется использовать [New].
type Pool[T Resetter] struct {
	pool sync.Pool
}

// New создаёт и возвращает указатель на инициализированный [Pool].
//
// Параметр newFunc задаёт функцию-фабрику, которая вызывается для создания
// нового экземпляра типа T в случае, если пул пуст. Если передать nil,
// метод [Pool.Get] при пустом пуле будет возвращать нулевое значение типа T.
func New[T Resetter](newFunc func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any {
				if newFunc == nil {
					var zero T
					return zero
				}
				return newFunc()
			},
		},
	}
}

// Get извлекает объект типа T из пула.
//
// Если пул в данный момент пуст, вызывается функция newFunc, переданная в [New].
// Метод безопасен для конкурентного вызова из нескольких горутин.
func (p *Pool[T]) Get() T {
	v := p.pool.Get()
	if v == nil {
		var zero T
		return zero
	}
	return v.(T)
}

// Put сбрасывает состояние объекта x путём вызова x.Reset() и помещает его в пул
// для дальнейшего переиспользования.
//
// После вызова Put вызывающий код не должен продолжать работу с объектом x,
// так как он может быть немедленно получен другой горутиной через [Pool.Get].
func (p *Pool[T]) Put(x T) {
	x.Reset()
	p.pool.Put(x)
}
