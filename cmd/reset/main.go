package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"strings"
)

const markerComment = "generate:reset"

type structInfo struct {
	Name   string
	Fields []*ast.Field
}

type packageInfo struct {
	Name    string
	Dir     string
	Structs []structInfo
}

func main() {
	rootDir := "."
	if len(os.Args) > 1 {
		rootDir = os.Args[1]
	}

	packages := make(map[string]*packageInfo)

	err := filepath.WalkDir(rootDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		// Пропускаем скрытые директории, vendor и сгенерированные файлы
		if d.IsDir() {
			name := d.Name()
			if name != "." && (strings.HasPrefix(name, ".") || name == "vendor") {
				return filepath.SkipDir
			}
			return nil
		}

		if !strings.HasSuffix(d.Name(), ".go") ||
			strings.HasSuffix(d.Name(), "_test.go") ||
			d.Name() == "reset.gen.go" {
			return nil
		}

		dir := filepath.Dir(path)
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("ошибка парсинга %s: %w", path, err)
		}

		foundStructs := extractResetableStructs(file)
		if len(foundStructs) == 0 {
			return nil
		}

		pkg, exists := packages[dir]
		if !exists {
			pkg = &packageInfo{
				Name: file.Name.Name,
				Dir:  dir,
			}
			packages[dir] = pkg
		}
		pkg.Structs = append(pkg.Structs, foundStructs...)

		return nil
	})

	if err != nil {
		log.Fatalf("Ошибка обхода директорий: %v", err)
	}

	for _, pkg := range packages {
		if err := generateFile(pkg); err != nil {
			log.Fatalf("Ошибка генерации для пакета %s: %v", pkg.Name, err)
		}
	}
}

// extractResetableStructs ищет структуры с комментарием // generate:reset
func extractResetableStructs(file *ast.File) []structInfo {
	var result []structInfo

	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}

		genDocHasMarker := hasMarker(genDecl.Doc)

		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}

			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}

			if genDocHasMarker || hasMarker(typeSpec.Doc) {
				result = append(result, structInfo{
					Name:   typeSpec.Name.Name,
					Fields: structType.Fields.List,
				})
			}
		}
	}

	return result
}

func hasMarker(cg *ast.CommentGroup) bool {
	if cg == nil {
		return false
	}
	for _, c := range cg.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if text == markerComment {
			return true
		}
	}
	return false
}

// generateFile формирует и записывает файл reset.gen.go в директории пакета
func generateFile(pkg *packageInfo) error {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg.Name)

	for _, st := range pkg.Structs {
		writeResetMethod(&buf, st)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("ошибка форматирования кода: %w\nисходный код:\n%s", err, buf.String())
	}

	outPath := filepath.Join(pkg.Dir, "reset.gen.go")
	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		return fmt.Errorf("ошибка записи файла %s: %w", outPath, err)
	}

	fmt.Printf("Сгенерирован файл: %s\n", outPath)
	return nil
}

func writeResetMethod(buf *bytes.Buffer, st structInfo) {
	recv := "rs"
	fmt.Fprintf(buf, "func (%s *%s) Reset() {\n", recv, st.Name)
	fmt.Fprintf(buf, "\tif %s == nil {\n\t\treturn\n\t}\n\n", recv)

	for _, field := range st.Fields {
		// Пропускаем встраиваемые (анонимные) поля без имени или обрабатываем их по имени типа
		if len(field.Names) == 0 {
			if ident, ok := getBaseIdent(field.Type); ok {
				generateFieldReset(buf, recv+"."+ident, field.Type, false)
			}
			continue
		}

		for _, name := range field.Names {
			if name.Name == "_" {
				continue
			}
			generateFieldReset(buf, recv+"."+name.Name, field.Type, false)
		}
	}

	fmt.Fprintf(buf, "}\n\n")
}

func getBaseIdent(expr ast.Expr) (string, bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name, true
	case *ast.StarExpr:
		return getBaseIdent(t.X)
	case *ast.SelectorExpr:
		return t.Sel.Name, true
	}
	return "", false
}

// generateFieldReset рекурсивно генерирует логику сброса для конкретного поля
func generateFieldReset(buf *bytes.Buffer, access string, expr ast.Expr, isDeref bool) {
	switch t := expr.(type) {
	case *ast.StarExpr:
		// Обработка указателей: проверяем на nil и сбрасываем разыменованное значение
		fmt.Fprintf(buf, "\tif %s != nil {\n", access)
		// Для указателя на структуру сначала проверяем наличие метода Reset()
		if isPossibleStruct(t.X) {
			fmt.Fprintf(buf, "\t\tif resetter, ok := any(%s).(interface{ Reset() }); ok {\n", access)
			fmt.Fprintf(buf, "\t\t\tresetter.Reset()\n")
			fmt.Fprintf(buf, "\t\t} else {\n")
			generateInnerPointerReset(buf, access, t.X, "\t\t\t")
			fmt.Fprintf(buf, "\t\t}\n")
		} else {
			generateInnerPointerReset(buf, access, t.X, "\t\t")
		}
		fmt.Fprintf(buf, "\t}\n")

	case *ast.ArrayType:
		// Если Len == nil, это слайс -> обрезаем до [:0]
		if t.Len == nil {
			fmt.Fprintf(buf, "\t%s = %s[:0]\n", access, access)
		} else {
			// Фиксированный массив зануляем целиком
			fmt.Fprintf(buf, "\t%s = %s{}\n", access, exprToString(t))
		}

	case *ast.MapType:
		// Мапы очищаем через встроенную функцию clear
		fmt.Fprintf(buf, "\tclear(%s)\n", access)

	case *ast.Ident:
		if zeroVal, ok := primitiveZeroValue(t.Name); ok {
			fmt.Fprintf(buf, "\t%s = %s\n", access, zeroVal)
		} else {
			// Пользовательский тип (структура или алиас)
			fmt.Fprintf(buf, "\tif resetter, ok := any(&%s).(interface{ Reset() }); ok {\n", access)
			fmt.Fprintf(buf, "\t\tresetter.Reset()\n")
			fmt.Fprintf(buf, "\t}\n")
		}

	case *ast.SelectorExpr:
		// Тип из другого пакета (например, time.Time или pkg.MyStruct)
		fmt.Fprintf(buf, "\tif resetter, ok := any(&%s).(interface{ Reset() }); ok {\n", access)
		fmt.Fprintf(buf, "\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t}\n")

	case *ast.StructType:
		// Анонимная вложенная структура: сбрасываем её поля напрямую
		for _, f := range t.Fields.List {
			for _, name := range f.Names {
				generateFieldReset(buf, access+"."+name.Name, f.Type, false)
			}
		}
	}
}

func generateInnerPointerReset(buf *bytes.Buffer, ptrAccess string, innerExpr ast.Expr, indent string) {
	switch inner := innerExpr.(type) {
	case *ast.Ident:
		if zeroVal, ok := primitiveZeroValue(inner.Name); ok {
			fmt.Fprintf(buf, "%s*%s = %s\n", indent, ptrAccess, zeroVal)
		} else {
			fmt.Fprintf(buf, "%s*%s = %s{}\n", indent, ptrAccess, inner.Name)
		}
	case *ast.ArrayType:
		if inner.Len == nil {
			fmt.Fprintf(buf, "%s*%s = (*%s)[:0]\n", indent, ptrAccess, ptrAccess)
		} else {
			fmt.Fprintf(buf, "%s*%s = %s{}\n", indent, ptrAccess, exprToString(inner))
		}
	case *ast.MapType:
		fmt.Fprintf(buf, "%sclear(*%s)\n", indent, ptrAccess)
	case *ast.StarExpr:
		// Указатель на указатель
		fmt.Fprintf(buf, "%sif *%s != nil {\n", indent, ptrAccess)
		generateInnerPointerReset(buf, "(*"+ptrAccess+")", inner.X, indent+"\t")
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		fmt.Fprintf(buf, "%s*%s = %s{}\n", indent, ptrAccess, exprToString(innerExpr))
	}
}

func isPossibleStruct(expr ast.Expr) bool {
	switch t := expr.(type) {
	case *ast.Ident:
		_, isPrim := primitiveZeroValue(t.Name)
		return !isPrim
	case *ast.SelectorExpr, *ast.StructType:
		return true
	}
	return false
}

func primitiveZeroValue(typeName string) (string, bool) {
	switch typeName {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"byte", "rune",
		"float32", "float64",
		"complex64", "complex128":
		return "0", true
	case "string":
		return `""`, true
	case "bool":
		return "false", true
	case "error":
		return "nil", true
	}
	return "", false
}

func exprToString(expr ast.Expr) string {
	var buf bytes.Buffer
	_ = format.Node(&buf, token.NewFileSet(), expr)
	return buf.String()
}
